import { expect } from "chai";
import { ethers } from "hardhat";
import { loadFixture } from "@nomicfoundation/hardhat-network-helpers";

import {
    OwnerPrivacyFirst,
    SenderPrivacyFirst,
} from "../../src/sdk/PFC";
import cipher from "../../testUtils/cipher";
import { ownerKeys } from "../../testUtils/constants";
import { testConfig, validPosition, validPosition2, BOND_DST } from "./_helpers/testConfigs";

describe("[E2E] SenderPrivacyFirst - PrivacyFirstContract", function () {

    async function deployFixture() {
        const [_owner, _sender, _sender2] = await ethers.getSigners();

        const DstFactory = await ethers.getContractFactory("DataSentTokenContract");
        const dstToken = await DstFactory.connect(_owner).deploy(999_999_999n);

        const PfcFactory = await ethers.getContractFactory("PrivacyFirstContract");
        const contract = await PfcFactory.connect(_owner).deploy(
            ownerKeys.publicKey,
            testConfig,
            await dstToken.getAddress(),
        );

        await dstToken.connect(_owner).transfer(_sender.address, BOND_DST);
        await dstToken.connect(_owner).transfer(_sender2.address, BOND_DST);

        return {
            contract, dstToken,
            owner:   new OwnerPrivacyFirst(_owner, contract, dstToken, ownerKeys, cipher),
            sender:  new SenderPrivacyFirst(_sender, contract, dstToken, cipher),
            sender2: new SenderPrivacyFirst(_sender2, contract, dstToken, cipher),
        };
    }

    let env: Awaited<ReturnType<typeof deployFixture>>;
    beforeEach(async function () {
        env = await loadFixture(deployFixture);
        await env.contract.removeAllListeners();
    });

    describe("enroll()", function () {
        it("completes the key exchange and stores Kenc", async function () {
            await env.owner.setup();
            await env.sender.enroll();

            expect(env.sender.isEnrolled()).to.equal(true);
            // Kenc held by the sender must match Kenc generated by the owner.
            expect(env.sender.getKenc()).to.equal(
                (env.owner as any).encryptionKeys.encryptionKey,
            );
        });

        it("hangs without an active owner listener (no auto-response)", async function () {
            // Skip owner.setup() - no listeners registered.
            const settled = await Promise.race([
                env.sender.enroll().then(() => "settled" as const),
                new Promise<"timeout">(r => setTimeout(() => r("timeout"), 300)),
            ]);
            expect(settled).to.equal("timeout");
            await env.contract.removeAllListeners();
        });

        it("rejects a second enrollment attempt from the same address", async function () {
            await env.owner.setup();
            await env.sender.enroll();

            // The SC's `publishEncryptedSenderPublicKey` reverts when the
            // sender has already requested to join.
            await expect(env.sender.enroll())
                .to.be.revertedWith("Sender has already requested to join");
        });
    });

    describe("payBond()", function () {
        it("moves the required bond amount from the sender to the contract", async function () {
            await env.owner.setup();
            await env.sender.enroll();

            const required = await env.contract.getRequiredSenderBond();
            const senderBefore = await env.dstToken.balanceOf(env.sender.getAddress());
            const contractBefore = await env.dstToken.balanceOf(await env.contract.getAddress());

            await env.sender.payBond();

            const senderAfter = await env.dstToken.balanceOf(env.sender.getAddress());
            const contractAfter = await env.dstToken.balanceOf(await env.contract.getAddress());

            expect(senderBefore - senderAfter).to.equal(required);
            expect(contractAfter - contractBefore).to.equal(required);
        });

        it("is a no-op when maxDataPerSender == 0 (unlimited mode)", async function () {
            // Redeploy with unlimited mode for this test.
            const [_owner, _sender] = await ethers.getSigners();
            const DstFactory = await ethers.getContractFactory("DataSentTokenContract");
            const dst = await DstFactory.connect(_owner).deploy(999_999_999n);
            const Pfc = await ethers.getContractFactory("PrivacyFirstContract");
            const c = await Pfc.connect(_owner).deploy(
                ownerKeys.publicKey,
                { ...testConfig, needs: { ...testConfig.needs, maxDataPerSender: 0 } },
                await dst.getAddress(),
            );

            const owner = new OwnerPrivacyFirst(_owner, c, dst, ownerKeys, cipher);
            const sender = new SenderPrivacyFirst(_sender, c, dst, cipher);

            await owner.setup();
            await sender.enroll();

            // No throw, no balance change.
            const before = await dst.balanceOf(_sender.address);
            await sender.payBond();
            const after = await dst.balanceOf(_sender.address);
            expect(after).to.equal(before);

            await c.removeAllListeners();
        });
    });

    describe("publishData()", function () {
        it("submits an encrypted CID that the owner can decrypt back to the plaintext", async function () {
            await env.owner.setup();
            await env.sender.setup();

            const plainCid = "QmRoundTripPlainCid";
            const tx = await env.sender.publishData(plainCid, validPosition);
            await tx.wait();

            // Recover the on-chain encryptedCid bytes.
            const [cids] = await env.contract.getCampaignData();
            const encryptedHex: string = cids[0];

            // Owner decrypts with Kdec (the matching half of Kenc).
            const ownerKdec = (env.owner as any).encryptionKeys.decryptionKey;
            const envelopeJson = ethers.toUtf8String(encryptedHex);
            const decrypted = cipher.decryptStringHybrid(ownerKdec, JSON.parse(envelopeJson));

            expect(decrypted).to.equal(plainCid);
        });

        it("throws when called before enroll()", async function () {
            await env.owner.setup();
            // sender NOT enrolled
            await expect(env.sender.publishData("QmNoEnroll", validPosition))
                .to.be.rejectedWith("Not enrolled");
        });

        it("rejects submissions exceeding maxDataPerSender", async function () {
            await env.owner.setup();
            await env.sender.setup();

            // maxDataPerSender = 5
            for (let i = 0; i < 5; i++) {
                const tx = await env.sender.publishData(`QmOver_${i}`, validPosition);
                await tx.wait();
            }

            // 6th submission must revert
            await expect(env.sender.publishData("QmOver_6", validPosition))
                .to.be.revertedWith("Max data limit reached");
        });
    });

    describe("setup()", function () {
        it("is equivalent to enroll() + payBond()", async function () {
            await env.owner.setup();
            await env.sender.setup();

            expect(env.sender.isEnrolled()).to.equal(true);
            const required = await env.contract.getRequiredSenderBond();
            // After setup() the contract holds the bond.
            expect(await env.dstToken.balanceOf(await env.contract.getAddress()))
                .to.equal(BigInt(testConfig.rewardConfig.totalDst) + required);
        });
    });
});
